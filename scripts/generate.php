<?php

declare(strict_types=1);

/*
 * Regenerates openapi.json and src/Generated/{Catalog,Scopes,Hints}.php. Runs only in the `regen`
 * compose service (`just regen`).
 *
 *     php scripts/generate.php [specPathOrUrl]     default: https://api.hushscript.com/openapi.json
 *
 * hints.json comes from $CONFORMANCE_DIR/hints.json when set, otherwise from the conformance repo at
 * the tag in the conformance-ref file. There is no client generator: the low-level layer is the
 * hand-written Api::request() (spec section 5).
 */

namespace Hushscript\Scripts;

const DEFAULT_SPEC = 'https://api.hushscript.com/openapi.json';
const HTTP_METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'];
const HEADER = "// Generated by scripts/generate.php from openapi.json and the conformance hints.json. Do not edit.\n";

/**
 * @return array<mixed>
 */
function record(mixed $value, string $what): array
{
    if (! is_array($value)) {
        throw new \InvalidArgumentException("{$what} must be an object");
    }

    return $value;
}

function nonEmptyString(mixed $value, string $what): string
{
    if (! is_string($value) || $value === '') {
        throw new \InvalidArgumentException("{$what} must be a non-empty string");
    }

    return $value;
}

function integer(mixed $value, string $what): int
{
    if (! is_int($value)) {
        throw new \InvalidArgumentException("{$what} must be an integer");
    }

    return $value;
}

function literal(string $text): string
{
    return var_export($text, true);
}

function wrap(string $class, string $body): string
{
    return "<?php\n\ndeclare(strict_types=1);\n\nnamespace Hushscript\\Generated;\n\n".HEADER."\nfinal class {$class}\n{\n{$body}\n}\n";
}

function emitCatalog(mixed $spec): string
{
    $catalog = record($spec, 'spec')['x-error-catalog'] ?? null;
    if (! is_array($catalog) || $catalog === []) {
        throw new \InvalidArgumentException('spec has no x-error-catalog');
    }
    $seen = [];
    $lines = [];
    foreach (array_values($catalog) as $index => $raw) {
        $entry = record($raw, "x-error-catalog[{$index}]");
        $slug = nonEmptyString($entry['slug'] ?? null, "x-error-catalog[{$index}].slug");
        if (isset($seen[$slug])) {
            throw new \InvalidArgumentException("duplicate error slug {$slug}");
        }
        $seen[$slug] = true;
        $code = integer($entry['code'] ?? null, "{$slug}.code");
        $status = integer($entry['status'] ?? null, "{$slug}.status");
        $meaning = nonEmptyString($entry['meaning'] ?? null, "{$slug}.meaning");
        $lines[] = '        '.literal($slug)." => ['code' => {$code}, 'status' => {$status}, 'meaning' => ".literal($meaning).'],';
    }

    return wrap('Catalog', "    /** @var array<string, array{code: int, status: int, meaning: string}> */\n    public const ENTRIES = [\n".implode("\n", $lines)."\n    ];");
}

function emitScopes(mixed $spec): string
{
    $paths = record(record($spec, 'spec')['paths'] ?? null, 'paths');
    $entries = [];
    foreach ($paths as $path => $item) {
        $operations = record($item, "paths.{$path}");
        foreach (HTTP_METHODS as $method) {
            if (! isset($operations[$method])) {
                continue;
            }
            $scope = record($operations[$method], "{$method} {$path}")['x-required-scope'] ?? null;
            if ($scope === null) {
                continue;
            }
            $entries[strtoupper($method).' '.$path] = nonEmptyString($scope, "{$method} {$path} x-required-scope");
        }
    }
    ksort($entries, SORT_STRING);
    $lines = [];
    foreach ($entries as $key => $scope) {
        $lines[] = '        '.literal((string) $key).' => '.literal($scope).',';
    }

    return wrap('Scopes', "    /** @var array<string, string> */\n    public const OPERATIONS = [\n".implode("\n", $lines)."\n    ];");
}

function emitHints(mixed $hints): string
{
    $table = record($hints, 'hints.json');
    if ($table === []) {
        throw new \InvalidArgumentException('hints.json is empty');
    }
    $lines = [];
    foreach ($table as $slug => $text) {
        $lines[] = '        '.literal((string) $slug).' => '.literal(nonEmptyString($text, "hints.{$slug}")).',';
    }

    return wrap('Hints', "    /** @var array<string, string> */\n    public const TABLE = [\n".implode("\n", $lines)."\n    ];");
}

function conformanceRef(string $root): string
{
    return trim(file_get_contents($root.'/conformance-ref') ?: '');
}

function fetchText(string $url): string
{
    if (! str_starts_with($url, 'https://')) {
        throw new \InvalidArgumentException("refusing to fetch {$url}");
    }
    $context = stream_context_create(['http' => ['timeout' => 60]]);
    $text = file_get_contents($url, false, $context);
    if ($text === false) {
        throw new \RuntimeException("GET {$url} failed");
    }

    return $text;
}

function loadHints(string $root): mixed
{
    $directory = getenv('CONFORMANCE_DIR');
    $text = is_string($directory) && $directory !== ''
        ? (string) file_get_contents($directory.'/hints.json')
        : fetchText('https://raw.githubusercontent.com/Hushscript/hushscript-sdk-conformance/'.conformanceRef($root).'/hints.json');

    return json_decode($text, true, 512, JSON_THROW_ON_ERROR);
}

function generate(string $root, string $source = DEFAULT_SPEC): void
{
    $specText = str_starts_with($source, 'https://') ? fetchText($source) : (string) file_get_contents($source);
    $spec = json_decode($specText, true, 512, JSON_THROW_ON_ERROR);
    $catalog = emitCatalog($spec);
    $scopes = emitScopes($spec);
    $hints = emitHints(loadHints($root));

    // The spec's own bytes: key order and formatting survive and the regen diff stays reviewable.
    file_put_contents($root.'/openapi.json', str_ends_with($specText, "\n") ? $specText : $specText."\n");
    file_put_contents($root.'/src/Generated/Catalog.php', $catalog);
    file_put_contents($root.'/src/Generated/Scopes.php', $scopes);
    file_put_contents($root.'/src/Generated/Hints.php', $hints);
}

if (PHP_SAPI === 'cli' && isset($_SERVER['argv'][0]) && realpath($_SERVER['argv'][0]) === __FILE__) {
    generate(dirname(__DIR__), $_SERVER['argv'][1] ?? DEFAULT_SPEC);
}
